-- Webloom subscriptions: free/pro plans, watermark gating, and customer
-- subscription requests. Additive only — existing rows keep plan='free'.

alter table public.profiles
  add column if not exists plan text not null default 'free',
  add column if not exists subscribed_at timestamptz;

alter table public.profiles drop constraint if exists profiles_plan_check;
alter table public.profiles
  add constraint profiles_plan_check check (plan in ('free', 'pro'));

-- Customers ask for Pro (watermark removal); staff approve and grant access.
create table if not exists public.subscription_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  email text not null,
  message text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users (id) on delete set null
);

create index if not exists subscription_requests_status_idx
  on public.subscription_requests (status, created_at desc);

alter table public.subscription_requests enable row level security;
revoke all on table public.subscription_requests from anon, authenticated;
grant select on table public.subscription_requests to authenticated;

-- Staff read requests through the authenticated server client, like audit logs.
drop policy if exists subscription_requests_read_admin on public.subscription_requests;
create policy subscription_requests_read_admin on public.subscription_requests
  for select to authenticated
  using ((select public.is_platform_admin()));

-- Grant or revoke a customer's subscription. Runs as the service role, so
-- customers cannot flip their own plan (profiles only grants update on
-- display_name to the owner).
create or replace function public.admin_set_user_plan(p_user_id uuid, p_plan text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_email text;
begin
  if not public.is_platform_admin() then
    raise exception 'Platform administrator permission required' using errcode = '42501';
  end if;
  if p_plan not in ('free', 'pro') then
    raise exception 'Invalid plan' using errcode = 'P0001';
  end if;

  update public.profiles
     set plan = p_plan,
         subscribed_at = case when p_plan = 'pro' then now() else null end,
         updated_at = now()
   where id = p_user_id
   returning email into target_email;
  if not found then
    raise exception 'Customer account not found' using errcode = 'P0002';
  end if;

  insert into public.audit_logs (actor_id, action, target_user_id, target_email, metadata)
  values (
    (select auth.uid()),
    case when p_plan = 'pro' then 'subscription_granted' else 'subscription_revoked' end,
    p_user_id,
    coalesce(target_email, ''),
    jsonb_build_object('plan', p_plan)
  );
end;
$$;

revoke all on function public.admin_set_user_plan(uuid, text) from public, anon;
grant execute on function public.admin_set_user_plan(uuid, text) to authenticated;

-- Approve/reject a subscription request. Approving an attached customer also
-- grants them the pro plan (which removes the watermark from their sites).
create or replace function public.admin_set_subscription_request_status(p_request_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_user_id uuid;
  target_email text;
begin
  if not public.is_platform_admin() then
    raise exception 'Platform administrator permission required' using errcode = '42501';
  end if;
  if p_status not in ('approved', 'rejected') then
    raise exception 'Invalid status' using errcode = 'P0001';
  end if;

  update public.subscription_requests
     set status = p_status,
         reviewed_at = now(),
         reviewed_by = (select auth.uid())
   where id = p_request_id
   returning user_id, email into target_user_id, target_email;
  if not found then
    raise exception 'Subscription request not found' using errcode = 'P0002';
  end if;

  if p_status = 'approved' and target_user_id is not null then
    update public.profiles
       set plan = 'pro', subscribed_at = now(), updated_at = now()
     where id = target_user_id;
  end if;

  insert into public.audit_logs (actor_id, action, target_user_id, target_email, metadata)
  values (
    (select auth.uid()),
    case p_status when 'approved' then 'subscription_request_approved' else 'subscription_request_rejected' end,
    target_user_id,
    coalesce(target_email, ''),
    jsonb_build_object('request_id', p_request_id, 'status', p_status)
  );
end;
$$;

revoke all on function public.admin_set_subscription_request_status(bigint, text) from public, anon;
grant execute on function public.admin_set_subscription_request_status(bigint, text) to authenticated;
