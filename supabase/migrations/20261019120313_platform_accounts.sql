-- The trigger accounts for a small row/index overhead in addition to the JSON
-- representation. Quota counter updates and the project write are one transaction.
create or replace function public.track_webloom_project_storage()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_bytes bigint;
  old_bytes bigint := 0;
  byte_delta bigint := 0;
  counter_value bigint;
  counter_rows bigint;
  project_max constant bigint := 1048576; -- 1 MiB per project, including overhead
  account_max constant bigint := 5242880; -- 5 MiB per account
  account_project_max constant integer := 25;
begin
  if tg_op = 'DELETE' then
    old_bytes := coalesce(old.data_bytes, 0);

    update public.webloom_cloud_storage_quota
       set used_bytes = greatest(0, used_bytes - old_bytes),
           updated_at = now()
     where singleton = true;

    update public.webloom_user_storage_usage
       set used_bytes = greatest(0, used_bytes - old_bytes),
           project_count = greatest(0, project_count - 1),
           updated_at = now()
     where user_id = old.user_id;

    return old;
  end if;

  new_bytes := octet_length(new.data::text)::bigint + 1024;
  if new_bytes > project_max then
    raise exception 'WEBLOOM_PROJECT_TOO_LARGE'
      using errcode = 'P0001', detail = 'A cloud-saved website is limited to 1 MiB. The local copy is still saved.';
  end if;

  if tg_op = 'UPDATE' then
    if new.user_id is distinct from old.user_id then
      raise exception 'WEBLOOM_OWNER_CHANGE_DENIED' using errcode = '42501';
    end if;
    if new.data is not distinct from old.data then
      new.data_bytes := old.data_bytes;
      return new;
    end if;
    old_bytes := coalesce(old.data_bytes, 0);
    byte_delta := new_bytes - old_bytes;
  else
    byte_delta := new_bytes;
  end if;

  update public.webloom_cloud_storage_quota
     set used_bytes = used_bytes + byte_delta,
         updated_at = now()
   where singleton = true
     and used_bytes + byte_delta <= limit_bytes
  returning used_bytes into counter_value;
  if not found then
    raise exception 'WEBLOOM_CLOUD_QUOTA_EXCEEDED'
      using errcode = 'P0001', detail = 'The shared Webloom cloud-save pool is full. This project remains saved on this device.';
  end if;

  if tg_op = 'INSERT' then
    insert into public.webloom_user_storage_usage as usage (user_id, used_bytes, project_count, updated_at)
    values (new.user_id, new_bytes, 1, now())
    on conflict (user_id) do update
      set used_bytes = usage.used_bytes + excluded.used_bytes,
          project_count = usage.project_count + 1,
          updated_at = now()
      where usage.used_bytes + excluded.used_bytes <= account_max
        and usage.project_count + 1 <= account_project_max
    returning used_bytes into counter_value;
    if not found then
      raise exception 'WEBLOOM_ACCOUNT_QUOTA_EXCEEDED'
        using errcode = 'P0001', detail = 'This account has reached its cloud-save allowance. The local copy is still saved.';
    end if;
  else
    update public.webloom_user_storage_usage
       set used_bytes = used_bytes + byte_delta,
           updated_at = now()
     where user_id = new.user_id
       and used_bytes + byte_delta <= account_max
    returning used_bytes into counter_value;
    if not found then
      raise exception 'WEBLOOM_ACCOUNT_QUOTA_EXCEEDED'
        using errcode = 'P0001', detail = 'This account has reached its cloud-save allowance. The local copy is still saved.';
    end if;
  end if;

  new.data_bytes := new_bytes;
  return new;
end;
$$;

revoke all on function public.track_webloom_project_storage() from public, anon, authenticated;
drop trigger if exists enforce_webloom_project_storage_quota on public.projects;
create trigger enforce_webloom_project_storage_quota
before insert or update of data, user_id or delete on public.projects
for each row execute function public.track_webloom_project_storage();

create or replace function public.webloom_cloud_storage_status()
returns table (
  project_count integer,
  account_used_bytes bigint,
  account_limit_bytes bigint,
  project_limit_bytes bigint,
  shared_used_bytes bigint,
  shared_limit_bytes bigint,
  shared_remaining_bytes bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    coalesce(u.project_count, 0),
    coalesce(u.used_bytes, 0),
    5242880::bigint,
    1048576::bigint,
    q.used_bytes,
    q.limit_bytes,
    greatest(0, q.limit_bytes - q.used_bytes)
  from public.webloom_cloud_storage_quota q
  left join public.webloom_user_storage_usage u on u.user_id = (select auth.uid())
  where q.singleton = true
    and (select auth.uid()) is not null;
$$;

revoke all on function public.webloom_cloud_storage_status() from public, anon;
grant execute on function public.webloom_cloud_storage_status() to authenticated;

create or replace function public.admin_set_user_suspension(p_user_id uuid, p_suspended boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_email text;
begin
  if not public.is_platform_admin() then
    raise exception 'Platform administrator permission required' using errcode = '42501';
  end if;
  if p_user_id = (select auth.uid()) then
    raise exception 'Administrators cannot pause their own account' using errcode = '42501';
  end if;
  if exists (select 1 from public.platform_admins a where a.user_id = p_user_id) then
    raise exception 'Administrator accounts cannot be paused from the customer dashboard' using errcode = '42501';
  end if;

  update public.profiles
     set suspended_at = case when p_suspended then now() else null end,
         updated_at = now()
   where id = p_user_id
   returning email into target_email;

  if not found then
    raise exception 'Customer account not found' using errcode = 'P0002';
  end if;

  insert into public.audit_logs (actor_id, action, target_user_id, target_email, metadata)
  values (
    (select auth.uid()),
    case when p_suspended then 'customer_suspended' else 'customer_restored' end,
    p_user_id,
    coalesce(target_email, ''),
    jsonb_build_object('suspended', p_suspended)
  );
end;
$$;

revoke all on function public.admin_set_user_suspension(uuid, boolean) from public, anon;
grant execute on function public.admin_set_user_suspension(uuid, boolean) to authenticated;

