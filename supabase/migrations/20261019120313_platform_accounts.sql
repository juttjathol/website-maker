create or replace function public.admin_storage_stats()
returns table (
  used_bytes bigint,
  limit_bytes bigint,
  cloud_project_count bigint,
  customers_with_cloud_projects bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_platform_admin() then
    raise exception 'Platform administrator permission required' using errcode = '42501';
  end if;
  return query
    select
      q.used_bytes,
      q.limit_bytes,
      (select count(*)::bigint from public.projects),
      (select count(*)::bigint from public.webloom_user_storage_usage where project_count > 0)
    from public.webloom_cloud_storage_quota q
    where q.singleton = true;
end;
$$;

