-- Webloom accounts, private projects, admin operations and hard cloud-storage caps.
-- This migration is intentionally Supabase/Postgres-only. Uploaded images are
-- compressed in the browser and remain inside project JSON; no Storage bucket is used.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null default '',
  display_name text not null default '',
  suspended_at timestamptz,
  must_change_password boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles
  add column if not exists must_change_password boolean not null default false;

create unique index if not exists profiles_email_lower_unique on public.profiles (lower(email)) where email <> '';
create index if not exists profiles_created_idx on public.profiles (created_at desc);

create table if not exists public.projects (
  id text primary key,
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  name text not null check (char_length(name) <= 160),
  data jsonb not null,
  data_bytes bigint not null default 0 check (data_bytes >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.projects
  add column if not exists data_bytes bigint not null default 0;

create index if not exists projects_user_updated_idx on public.projects (user_id, updated_at desc);

-- Webloom-managed portion of the 500 MB Supabase Free database budget.
-- 160 MiB is reserved for project payloads; the remainder is left for Auth,
-- profiles, indexes, audit records and database overhead. This is a hard cap,
-- not a promise that 50,000 users can all cloud-save large sites.
create table if not exists public.webloom_cloud_storage_quota (
  singleton boolean primary key default true check (singleton),
  used_bytes bigint not null default 0 check (used_bytes >= 0),
  limit_bytes bigint not null default 167772160 check (limit_bytes > 0),
  updated_at timestamptz not null default now()
);

insert into public.webloom_cloud_storage_quota (singleton, used_bytes, limit_bytes)
values (true, 0, 167772160)
on conflict (singleton) do update
  set limit_bytes = excluded.limit_bytes,
      updated_at = now();

create table if not exists public.webloom_user_storage_usage (
  user_id uuid primary key references auth.users (id) on delete cascade,
  used_bytes bigint not null default 0 check (used_bytes >= 0),
  project_count integer not null default 0 check (project_count >= 0),
  updated_at timestamptz not null default now()
);

-- Repair counters safely if this migration is reapplied to a pre-existing install.
update public.projects
   set data_bytes = octet_length(data::text)::bigint + 1024
 where data_bytes = 0;

insert into public.webloom_user_storage_usage (user_id, used_bytes, project_count, updated_at)
select user_id, sum(data_bytes)::bigint, count(*)::integer, now()
  from public.projects
 group by user_id
on conflict (user_id) do update
  set used_bytes = excluded.used_bytes,
      project_count = excluded.project_count,
      updated_at = now();

update public.webloom_cloud_storage_quota
   set used_bytes = coalesce((select sum(data_bytes)::bigint from public.projects), 0),
       updated_at = now()
 where singleton = true;

create table if not exists public.platform_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users (id) on delete set null,
  action text not null,
  target_user_id uuid references auth.users (id) on delete set null,
  target_email text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_logs_created_idx on public.audit_logs (created_at desc);

create or replace function public.handle_auth_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_name text;
begin
  profile_name := coalesce(
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'name', ''),
    ''
  );

  insert into public.profiles (id, email, display_name, must_change_password, created_at, updated_at)
  values (
    new.id,
    coalesce(new.email, ''),
    profile_name,
    coalesce((new.raw_app_meta_data ->> 'webloom_must_change_password')::boolean, false),
    coalesce(new.created_at, now()),
    now()
  )
  on conflict (id) do update
    set email = excluded.email,
        display_name = case when excluded.display_name <> '' then excluded.display_name else public.profiles.display_name end,
        updated_at = now();
  return new;
end;
$$;

revoke all on function public.handle_auth_user_profile() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_or_updated on auth.users;
create trigger on_auth_user_created_or_updated
after insert or update of email on auth.users
for each row execute function public.handle_auth_user_profile();

